-- Q61. What is the overall churn rate?
SELECT COUNT(DISTINCT subscription_id) AS churned_subscriptions,
       (SELECT COUNT(*) FROM subscriptions) AS total_subscriptions,
       ROUND(COUNT(DISTINCT subscription_id) * 100.0 / (SELECT COUNT(*) FROM subscriptions), 2) AS churn_rate_pct
FROM churn_events;

-- Q62. What is the monthly churn trend?
SELECT YEAR(churn_date) AS churn_year,
       MONTH(churn_date) AS churn_month,
       COUNT(DISTINCT subscription_id) AS churned_subscriptions
FROM churn_events
GROUP BY YEAR(churn_date), MONTH(churn_date)
ORDER BY churn_year, churn_month;

-- Q63. Which plan tier has the highest churn rate?
SELECT p.tier,
       COUNT(DISTINCT s.subscription_id) AS total_subscriptions,
       COUNT(DISTINCT ce.subscription_id) AS churned_subscriptions,
       ROUND(COUNT(DISTINCT ce.subscription_id) * 100.0 / COUNT(DISTINCT s.subscription_id), 2) AS churn_rate_pct
FROM subscriptions s
JOIN plans p
ON s.plan_id = p.plan_id
LEFT JOIN churn_events ce
ON s.subscription_id = ce.subscription_id
GROUP BY p.tier
ORDER BY churn_rate_pct DESC;

-- Q64. Does contract type affect churn?
SELECT s.contract_type,
       COUNT(DISTINCT s.subscription_id) AS total_subscriptions,
       COUNT(DISTINCT ce.subscription_id) AS churned_subscriptions,
       ROUND(COUNT(DISTINCT ce.subscription_id) * 100.0 / COUNT(DISTINCT s.subscription_id), 2) AS churn_rate_pct
FROM subscriptions s
LEFT JOIN churn_events ce
ON s.subscription_id = ce.subscription_id
GROUP BY s.contract_type
ORDER BY churn_rate_pct DESC;

-- Q65. What are the most common cancellation reason categories?
SELECT cr.reason_category, COUNT(*) AS churn_count
FROM churn_events ce
JOIN cancellation_reasons cr
ON ce.reason_id = cr.reason_id
GROUP BY cr.reason_category
ORDER BY churn_count DESC;

-- Q66. How much monthly revenue is lost because of churned subscriptions?
SELECT SUM(p.monthly_price) AS monthly_revenue_lost
FROM subscriptions s
JOIN plans p
ON s.plan_id = p.plan_id
WHERE s.subscription_id IN (SELECT subscription_id FROM churn_events);

-- Q67. Which zones have the highest churn?
SELECT r.zone, COUNT(DISTINCT ce.subscription_id) AS churned_subscriptions
FROM churn_events ce
JOIN customer_addresses ca
ON ce.customer_id = ca.customer_id
JOIN regions r
ON ca.region_id = r.region_id
GROUP BY r.zone
ORDER BY churned_subscriptions DESC;

-- Q68. Compare the average NPS score of churned and active customers.
SELECT CASE WHEN ce.customer_id IS NULL THEN 'Active' ELSE 'Churned' END AS customer_type,
       ROUND(AVG(n.nps_score), 2) AS avg_nps
FROM nps_feedback n
LEFT JOIN (SELECT DISTINCT customer_id FROM churn_events) ce
ON n.customer_id = ce.customer_id
GROUP BY customer_type;

-- Q69. Do churned customers raise more support tickets?
WITH ticket_count AS (
    SELECT customer_id, COUNT(*) AS tickets
    FROM support_tickets
    GROUP BY customer_id
)
SELECT CASE WHEN ce.customer_id IS NULL THEN 'Active' ELSE 'Churned' END AS customer_type,
       ROUND(AVG(COALESCE(tc.tickets, 0)), 2) AS avg_tickets_per_customer
FROM customers c
LEFT JOIN ticket_count tc
ON c.customer_id = tc.customer_id
LEFT JOIN (SELECT DISTINCT customer_id FROM churn_events) ce
ON c.customer_id = ce.customer_id
GROUP BY customer_type;

-- Q70. Find the top 10 churned customers by total amount paid.
SELECT c.customer_id, c.first_name, SUM(pay.amount) AS total_paid
FROM customers c
JOIN subscriptions s
ON c.customer_id = s.customer_id
JOIN invoices i
ON s.subscription_id = i.subscription_id
JOIN payments pay
ON i.invoice_id = pay.invoice_id
WHERE pay.status = 'Success'
AND c.customer_id IN (SELECT customer_id FROM churn_events)
GROUP BY c.customer_id, c.first_name
ORDER BY total_paid DESC
LIMIT 10;

-- Q71. What is the average customer lifetime (in months) before churn?
SELECT ROUND(AVG(DATEDIFF(x.churn_date, s.start_date)) / 30, 1) AS avg_lifetime_months
FROM subscriptions s
JOIN (SELECT subscription_id, MIN(churn_date) AS churn_date
      FROM churn_events
      GROUP BY subscription_id) x
ON s.subscription_id = x.subscription_id;

-- Q72. Rank cancellation reasons by number of churn events.
SELECT reason_text, churn_count,
       RANK() OVER (ORDER BY churn_count DESC) AS reason_rank
FROM (
    SELECT cr.reason_text, COUNT(*) AS churn_count
    FROM churn_events ce
    JOIN cancellation_reasons cr
    ON ce.reason_id = cr.reason_id
    GROUP BY cr.reason_id, cr.reason_text
) t
ORDER BY reason_rank
LIMIT 10;

-- Q73. Which marketing channel brings customers with the highest churn rate?
SELECT mc.channel,
       COUNT(DISTINCT s.subscription_id) AS total_subscriptions,
       COUNT(DISTINCT ce.subscription_id) AS churned_subscriptions,
       ROUND(COUNT(DISTINCT ce.subscription_id) * 100.0 / COUNT(DISTINCT s.subscription_id), 2) AS churn_rate_pct
FROM marketing_campaigns mc
JOIN customers c
ON mc.campaign_id = c.campaign_id
JOIN subscriptions s
ON c.customer_id = s.customer_id
LEFT JOIN churn_events ce
ON s.subscription_id = ce.subscription_id
GROUP BY mc.channel
ORDER BY churn_rate_pct DESC;
